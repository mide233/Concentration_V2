        void drawVerticalRotatedString(uint8_t x, uint8_t y, const char *str);
        void drawText(uint8_t percent);

        OledPanel panel_;
        uint8_t logicBuffer_[kLogicBufferSize]; // 32x128 逻辑图形缓冲（按页存放）
        uint8_t dotExist_;
