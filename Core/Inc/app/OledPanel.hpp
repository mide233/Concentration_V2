// 取字符字模索引；标准字库覆盖 0x20..0x7E，越界返回 255
inline uint8_t glyphIndex(char ch) {
    const auto code = static_cast<unsigned char>(ch);
    if (code < 0x20 || code > 0x7E)
        return 255;
    return static_cast<uint8_t>(code - 0x20);
}

inline constexpr uint8_t kOledAddress = 0x78; // 7 位地址 0x3C 左移一位
inline constexpr uint32_t kI2cTimeoutMs = 100;

/*
 * SSD1306（128x32，I2C1）底层驱动。
 * 仅负责命令/数据发送、缓冲清零与按页刷新，以及物理像素的置位；
 * 不涉及图形布局与旋转（见 Display）。
 */
class OledPanel {
public:
    static constexpr uint8_t kWidth = 128;
    static constexpr uint8_t kHeight = 32;
    static constexpr uint8_t kPageBits = 8;
    static constexpr uint16_t kBufferSize = kWidth * (kHeight / kPageBits); // 512

    // 上电延时 + SSD1306 初始化序列（含 clear + refresh）
    void init() {
        HAL_Delay(100);
        writeCommand(0xAE); // display off
        writeCommand(0xD5);
        writeCommand(0x80);
        writeCommand(0xA8);
        writeCommand(0x1F); // multiplex 1/32
        writeCommand(0xD3);
        writeCommand(0x00);
        writeCommand(0x40);
        writeCommand(0x8D);
        writeCommand(0x14); // charge pump on
        writeCommand(0x20);
        writeCommand(0x00);
        writeCommand(0xA0);
        writeCommand(0xC0);
        writeCommand(0xDA);
        writeCommand(0x02);
        writeCommand(0x81);
        writeCommand(0x8F);
        writeCommand(0xD9);
        writeCommand(0xF1);
        writeCommand(0xDB);
        writeCommand(0x40);
        writeCommand(0xA4);
        writeCommand(0xA6);
        writeCommand(0x2E);
        writeCommand(0xAF); // display on

        clear();
        refresh();
    }

    // 清空物理缓冲
    void clear() { std::memset(buffer_, 0, sizeof(buffer_)); }

    // 将物理缓冲整帧写入面板（方案 C：DMA 传输，主循环不再阻塞等待）。
    // 依赖 init() 已设置的“水平寻址模式”（0x20 0x00）：设置列 0..127、页 0..3 后，
    // 本次 513 字节（0x40 + 512）会连续覆盖全部 4 页。
    void refresh() {
        // 若上一帧 DMA 尚未结束，先等待，避免并发改写 txBuffer_（正常已空闲）。
        const uint32_t start = HAL_GetTick();
        while (HAL_I2C_GetState(&hi2c1) == HAL_I2C_STATE_BUSY_TX) {
            if (HAL_GetTick() - start >= kI2cTimeoutMs) {
                break; // 异常保护：交由 HAL 错误回调/超时处理
            }
        }

        // 设置水平寻址窗口：列 0..127，页 0..3（一条命令事务）
        uint8_t cmd[7] = {0x00, 0x21, 0x00, 0x7F, 0x22, 0x00, 0x03};
        HAL_I2C_Master_Transmit(&hi2c1, kOledAddress, cmd, sizeof(cmd), kI2cTimeoutMs);

        // 控制字 0x40 + 512 字节显存，单次 DMA 发送后立即返回（约 11.5 ms @400 kHz）
        txBuffer_[0] = 0x40;
        std::memcpy(&txBuffer_[1], buffer_, kBufferSize);
        HAL_I2C_Master_Transmit_DMA(&hi2c1, kOledAddress, txBuffer_, sizeof(txBuffer_));
    }

    // 物理坐标置位（超界忽略）
    void setPixel(uint8_t x, uint8_t y) {
        if (x >= kWidth || y >= kHeight)
            return;
        buffer_[(y / kPageBits) * kWidth + x] |= static_cast<uint8_t>(1u << (y % kPageBits));
    }

private:
    // 写命令字节（控制字 0x00 + 命令）
    static void writeCommand(uint8_t command) {
        uint8_t buf[2] = {0x00, command};
        HAL_I2C_Master_Transmit(&hi2c1, kOledAddress, buf, 2, kI2cTimeoutMs);
    }

    // 写数据字节（控制字 0x40 + 数据）
    static void writeData(uint8_t data) {
        uint8_t buf[2] = {0x40, data};
        HAL_I2C_Master_Transmit(&hi2c1, kOledAddress, buf, 2, kI2cTimeoutMs);
    }

    static inline uint8_t txBuffer_[1 + kBufferSize]; // DMA 发送缓冲（需稳定地址）
    uint8_t buffer_[kBufferSize];                     // 128x32 物理缓冲（按页存放）
};

